"""Replay Swift-produced Explorer uploads against the real API routes.

``tests/fixtures/explorer/upload-vectors.json`` is generated by APGI-Explorer
(``scripts/generate_swift_vectors.py``) and is byte-identical to the file its
portable Swift tests check against Swift's own canonical JSON, SHA-256 and event-key
code. This module sends those exact events through the real FastAPI app, database and
consent checks. It covers duplicate handling, hash mismatches, conflicting reuse and
consent gating. It does not exercise HTTPS, deployment or iOS/macOS background sessions.
"""

import copy
import json
from pathlib import Path
from typing import Any

from app.services import explorer_contract as contract
from tests.integration.test_explorer_contract import _session
from tests.integration.test_reporting_integration import _client, db_engine  # noqa: F401

VECTORS: dict[str, Any] = json.loads(
    (Path(__file__).resolve().parents[1] / "fixtures/explorer/upload-vectors.json").read_text(
        "utf-8"
    )
)
EVENTS: list[dict[str, Any]] = VECTORS["events"]


def _wire(events: list[dict[str, Any]]) -> dict[str, Any]:
    keys = ("event_id", "seq_no", "payload", "payload_sha256")
    return {"events": [{k: e[k] for k in keys} for e in events]}


def _post(client: Any, psid: str, events: list[dict[str, Any]]) -> Any:
    return client.post(f"/v1/participant-sessions/{psid}/events", json=_wire(events))


def _enrolled(db_engine: Any) -> tuple[Any, str, str]:  # noqa: F811
    """Like ``_session`` but also returns the participant id (needed to revoke consent)."""
    r = _client(db_engine, ["researcher"], "researcher-1")
    study = r.post("/v1/studies", json={"name": "S"}).json()["study_id"]
    battery = r.post(
        "/v1/batteries", json={"study_id": study, "name": "B", "version": "1.0", "form_label": "A"}
    ).json()["battery_id"]
    c = _client(db_engine, ["viewer"], "u1")
    pid = c.post("/v1/participants", json={}).json()["participant_id"]
    for purpose in ("research_participation", "product_use"):
        assert (
            c.post(f"/v1/participants/{pid}/consents", json={"consent_type": purpose}).status_code
            == 201
        )
    resp = c.post(
        "/v1/participant-sessions",
        json={"participant_id": pid, "study_id": study, "battery_id": battery},
    )
    assert resp.status_code == 201, resp.text
    return c, resp.json()["participant_session_id"], pid


def test_swift_canonical_bytes_and_digests_match_the_server() -> None:
    assert VECTORS["instrument_sha256"] == contract.item_bank()["sha256"]
    for vector in VECTORS["canonical_vectors"]:
        assert contract.canonical_json(vector["payload"]) == vector["canonical"]
        assert contract.sha256_hex(vector["canonical"]) == vector["sha256"]
    for event in [*EVENTS, VECTORS["conflicting_event_for_seq_0"]]:
        assert contract.canonical_json(event["payload"]) == event["canonical"]
        assert contract.sha256_hex(event["canonical"]) == event["payload_sha256"]
        assert contract.validate_payload(event["payload"]) is None


def test_swift_batch_is_accepted_then_acknowledged_as_duplicate(
    db_engine: Any,
) -> None:  # noqa: F811
    c, psid = _session(db_engine)
    first = _post(c, psid, EVENTS)
    assert first.status_code == 200, first.text
    acks = first.json()["acks"]
    assert [a["status"] for a in acks] == ["accepted"] * 35
    assert [(a["event_id"], a["seq_no"], a["payload_sha256"]) for a in acks] == [
        (e["event_id"], e["seq_no"], e["payload_sha256"]) for e in EVENTS
    ]
    assert all(a["server_verified"] for a in acks)

    replay = _post(c, psid, EVENTS).json()["acks"]
    assert [a["status"] for a in replay] == ["duplicate"] * 35
    assert all(a["server_verified"] for a in replay)


def test_lost_acknowledgement_resend_accepts_only_the_missing_events(
    db_engine: Any,
) -> None:  # noqa: F811
    c, psid = _session(db_engine)
    assert (
        _post(c, psid, EVENTS[:10]).status_code == 200
    )  # server stored them; the client lost the ack
    acks = _post(c, psid, EVENTS).json()[
        "acks"
    ]  # the client resends everything it never saw verified
    assert [a["status"] for a in acks] == ["duplicate"] * 10 + ["accepted"] * 25
    scores = c.get(f"/v1/participant-sessions/{psid}/explorer-result").json()["scores"]
    answers = {e["payload"]["item_id"]: e["payload"]["value"] for e in EVENTS}
    assert scores == contract.allowlisted(contract.score_answers(answers))


def test_hash_mismatches_are_rejected_and_store_nothing(db_engine: Any) -> None:  # noqa: F811
    c, psid = _session(db_engine)
    wrong_digest = copy.deepcopy(EVENTS[0])
    wrong_digest["payload_sha256"] = EVENTS[1]["payload_sha256"]
    edited_payload = copy.deepcopy(EVENTS[0])
    edited_payload["payload"]["value"] = 4  # digest still describes the original value
    assert _post(c, psid, [wrong_digest]).status_code == 422
    assert _post(c, psid, [edited_payload]).status_code == 422
    # A bad event poisons its whole batch: the valid first event must not have been stored.
    assert _post(c, psid, [EVENTS[1], wrong_digest]).status_code == 422
    assert [a["status"] for a in _post(c, psid, EVENTS[:2]).json()["acks"]] == [
        "accepted",
        "accepted",
    ]


def test_conflicting_reuse_of_a_key_or_sequence_is_409(db_engine: Any) -> None:  # noqa: F811
    c, psid = _session(db_engine)
    assert _post(c, psid, [EVENTS[0]]).status_code == 200
    assert _post(c, psid, [VECTORS["conflicting_event_for_seq_0"]]).status_code == 409
    other_key = copy.deepcopy(EVENTS[0])
    other_key["event_id"] = EVENTS[1]["event_id"]
    assert _post(c, psid, [other_key]).status_code == 409  # same seq_no, different key
    other_seq = copy.deepcopy(EVENTS[0])
    other_seq["seq_no"] = 9
    assert _post(c, psid, [other_seq]).status_code == 409  # same key, different seq_no
    assert [a["status"] for a in _post(c, psid, [EVENTS[0]]).json()["acks"]] == ["duplicate"]


def test_upload_needs_both_product_and_research_consent(db_engine: Any) -> None:  # noqa: F811
    # A session can be created with research consent alone; upload still needs product_use as well.
    c, psid = _session(db_engine, consents=("research_participation",))
    assert _post(c, psid, EVENTS[:1]).status_code == 403


def test_withdrawal_of_either_required_consent_stops_uploads(db_engine: Any) -> None:  # noqa: F811
    for withdrawn in ("research_participation", "product_use"):
        c, psid, pid = _enrolled(db_engine)
        assert _post(c, psid, EVENTS[:5]).status_code == 200
        revoke = c.post(f"/v1/participants/{pid}/consents/revoke", json={"consent_type": withdrawn})
        assert revoke.status_code == 204, revoke.text
        assert _post(c, psid, EVENTS[5:10]).status_code == 403, withdrawn
        assert (
            _post(c, psid, EVENTS[:5]).status_code == 403
        ), withdrawn  # a replay needs live consent too
